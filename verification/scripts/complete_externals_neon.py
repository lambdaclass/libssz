"""Completes TypesExternal.lean and FunsExternal.lean of the AArch64 SHA-256 kernel of
libssz-merkle (`crates/ssz-merkle/src/neon.rs`) from the templates Aeneas generates.

Usage: python3 complete_externals_neon.py DIR
     (DIR has TypesExternal_Template.lean and FunsExternal_Template.lean; the script writes
     TypesExternal.lean and FunsExternal.lean and deletes the templates)

`neon.rs` uses eight intrinsics from `core::arch::aarch64`, the type `uint32x4_t` and
`core::hint::black_box`. None of them has a Rust body Aeneas can translate, so it leaves them
as `axiom`. Here:

* `uint32x4_t`: four 32-bit lanes (`Libssz.MerkleNeon.U32x4`);
* the eight intrinsics: the models in `Libssz/MerkleNeon/Intrinsics.lean`. None of them
  fails. The immediates (`LANE`, `IMM5`, a Rust const generic) arrive as a first `Std.I32`
  argument and are passed to the model as a natural number; the `u32`s are passed with the
  same 32 bits;
* `black_box`: not defined here. The x86 kernel extraction
  (`Libssz/Merkle/Code/FunsExternal.lean`) already defines it (the identity), and both
  extractions are imported together in the hasher proofs. The script removes the declaration
  from the template and imports that one. It is not a new assumption.

It is the same technique as for the x86 kernel (`complete_externals_merkle.py`), which comes
from gattaca-com/silver. If any template has any other `axiom`, the script fails: it has to be
inspected by hand.
"""
import os
import sys

M = "Libssz.MerkleNeon"
V = "core.core_arch.arm_shared.neon.uint32x4_t"
G = "core.core_arch.arm_shared.neon.generated"


def signature(name, ty):
    return (f'@[rust_fun "core::core_arch::arm_shared::neon::generated::{name}"]\n'
            f"axiom {G}.{name}\n{ty}")


# (name, signature Aeneas generates, body added to it)
FUNCTIONS = [
    ("vaddq_u32",
     signature("vaddq_u32", f"""  :
  {V} →
    {V} → Result
    {V}
"""),
     f"fun a b => ok ({M}.vaddq_u32 a b)"),
    ("vdupq_n_u32",
     signature("vdupq_n_u32", f"""  : Std.U32 → Result {V}
"""),
     f"fun x => ok ({M}.vdupq_n_u32 (UInt32.ofBitVec x.bv))"),
    ("vgetq_lane_u32",
     signature("vgetq_lane_u32", f"""  (IMM5 : Std.I32) :
  {V} → Result Std.U32
"""),
     f"fun v => ok ⟨({M}.vgetq_lane_u32 IMM5.bv.toNat v).toBitVec⟩"),
    ("vsetq_lane_u32",
     signature("vsetq_lane_u32", f"""  (LANE : Std.I32) :
  Std.U32 → {V} → Result
    {V}
"""),
     f"fun x v => ok ({M}.vsetq_lane_u32 LANE.bv.toNat (UInt32.ofBitVec x.bv) v)"),
    ("vsha256h2q_u32",
     signature("vsha256h2q_u32", f"""  :
  {V} →
    {V} →
    {V} → Result
    {V}
"""),
     f"fun e a k => ok ({M}.vsha256h2q_u32 e a k)"),
    ("vsha256hq_u32",
     signature("vsha256hq_u32", f"""  :
  {V} →
    {V} →
    {V} → Result
    {V}
"""),
     f"fun a e k => ok ({M}.vsha256hq_u32 a e k)"),
    ("vsha256su0q_u32",
     signature("vsha256su0q_u32", f"""  :
  {V} →
    {V} → Result
    {V}
"""),
     f"fun a b => ok ({M}.vsha256su0q_u32 a b)"),
    ("vsha256su1q_u32",
     signature("vsha256su1q_u32", f"""  :
  {V} →
    {V} →
    {V} → Result
    {V}
"""),
     f"fun a b c => ok ({M}.vsha256su1q_u32 a b c)"),
]

BLACK_BOX = """@[rust_fun "core::hint::black_box"]
axiom core.hint.black_box {T : Type _} : T → Result T
"""


def remove_block(src, decl):
    """Removes `decl` and the doc comment that precedes it."""
    assert src.count(decl) == 1, f"the declaration {decl.splitlines()[-1]!r} changed"
    i = src.index(decl)
    doc = src.rindex("/--", 0, i)
    assert "-/" in src[doc:i] and src[src.index("-/", doc) + 2:i].strip() == "", \
        "the declaration does not have the expected comment"
    return src[:doc] + src[i + len(decl):]


def complete_functions(src):
    src = src.replace(
        '-- This is a template file: rename it to "FunsExternal.lean" and fill the holes.',
        "-- Generated by scripts/complete_externals_neon.py from the Aeneas template.")
    imports = "public import Libssz.MerkleNeon.Code.Types\n"
    assert src.count(imports) == 1, "the header of the functions template changed"
    src = src.replace(imports, imports + "public import Libssz.Merkle.Code.FunsExternal\n")
    src = remove_block(src, BLACK_BOX)
    for name, decl, body in FUNCTIONS:
        assert src.count(decl) == 1, f"the signature of {name} changed in the template"
        definition = decl.replace("\naxiom ", "\ndef ", 1).rstrip("\n")
        comment = "/- Hand-written model: see `Libssz/MerkleNeon/Intrinsics.lean`. -/\n"
        src = src.replace(decl, comment + definition + " :=\n  " + body + "\n")
    assert "axiom" not in src, "an axiom was left without a model in FunsExternal"
    return src


TYPE = f"""@[rust_type "core::core_arch::arm_shared::neon::uint32x4_t"]
axiom {V} : Type
"""


def complete_types(src):
    src = src.replace(
        '-- This is a template file: rename it to "TypesExternal.lean" and fill the holes.',
        "-- Generated by scripts/complete_externals_neon.py from the Aeneas template.")
    imports = "public import Aeneas\n"
    assert src.count(imports) == 1, "the header of the types template changed"
    src = src.replace(imports, imports + f"public import {M}.Intrinsics\n")
    assert src.count(TYPE) == 1, "the declaration of uint32x4_t changed in the template"
    src = src.replace(TYPE, f"""/- Hand-written model: see `Libssz/MerkleNeon/Intrinsics.lean`. -/
@[rust_type "core::core_arch::arm_shared::neon::uint32x4_t"]
abbrev {V} : Type := {M}.U32x4
""")
    assert "axiom" not in src, "an axiom was left without a model in TypesExternal"
    return src


def main():
    folder = sys.argv[1]
    for name, complete in [("TypesExternal", complete_types),
                           ("FunsExternal", complete_functions)]:
        template = os.path.join(folder, f"{name}_Template.lean")
        with open(template) as f:
            src = complete(f.read())
        with open(os.path.join(folder, f"{name}.lean"), "w") as f:
            f.write(src)
        os.remove(template)
    print("models plugged in:", len(FUNCTIONS), "intrinsics and uint32x4_t")


if __name__ == "__main__":
    main()

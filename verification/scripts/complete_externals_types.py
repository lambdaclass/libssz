"""Links the extraction of libssz-types with those of the tree and the codec.

Usage: python3 complete_externals_types.py DIR
     (DIR has Types.lean, Funs.lean and FunsExternal_Template.lean of libssz-types; the
     script rewrites Types.lean and Funs.lean, writes FunsExternal.lean and deletes the
     template)

`crates/ssz-types` uses things from two other crates: from the tree (`ssz-merkle`: the
`HashTreeRoot` trait, `merkleize_in_place`, the `hash_tree_root` of `u64`, …) and from the
codec (`ssz`: the `SszEncode` trait, `ContainerEncoder` and the `SszEncode` implementations).
Each declaration from another crate is replaced by the one with the same Rust path in the
tree extraction (`Libssz/Merkle/Code/`) or, if the tree does not have it, in the codec
extraction (`Libssz/Code/`). How, and what has to be trusted, is explained in `link.py`.

The aliases in FunsExternal.lean go in the `libssz_types` namespace, so that they do not clash
with the names of the other two extractions.

**Universes.** The `Type _` binders of this extraction become `Type`. `Iterator::collect`, in
the Aeneas library, requires `Self : Type`, so the `hash_tree_root` of `SszList<T, N>` ends up
with `T : Type`, and the `HashTreeRoot` implementation (`impl_def`), which declares
`T : Type _`, does not match. Rust types all live in `Type`: the model does not change.

**`SmallVec`.** The only thing from another crate that is not in the other two extractions is
the `SmallVec` of the `smallvec` crate, used by `SszBitlist` and `SszBitvector`. The type and
its five functions are replaced by the hand-written model in
`Libssz/SszTypes/SmallVecModel.lean` (see there for what is assumed). The `smallvec::Array`
trait and its implementation for `[T; 64]`, which Aeneas does translate, are left as they are.

If any other declaration from another crate is missing from the other two extractions, or if
any `axiom` is left, the script fails.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import link  # noqa: E402

OWN = "libssz_types::"
M = "Libssz.SmallVecModel"

# The `smallvec` holes and their models: Lean name → body.
MODELS = {
    "smallvec.SmallVec.truncate": f"fun v len => {M}.truncate v len",
    "smallvec.SmallVec.from_slice": f"fun s => {M}.from_slice s",
    "smallvec.SmallVec.Insts.CoreOpsDerefDerefSlice.deref": f"fun v => {M}.deref v",
    "smallvec.SmallVec.Insts.CoreOpsIndexIndexMut.index_mut":
        "alloc.vec.Vec.index_mut coresliceindexSliceIndexISliceClause1_OutputInst",
    "ArrayT64.Insts.SmallvecArray.size": "ok 64#usize",
}
TYPE = """@[rust_type "smallvec::SmallVec"]
axiom smallvec.SmallVec (A : Type) (Clause0_Item : Type) : Type
"""


def from_smallvec(path):
    return path.startswith("smallvec::")


def models(src):
    """Replaces the `smallvec` holes with the model from SmallVecModel.lean."""
    out = []
    for b in src.split("\n\n"):
        m = link.re.search(r"^axiom (\S+)", b, link.re.M)
        if m and m.group(1) in MODELS:
            name = m.group(1)
            b = b.replace("\naxiom ", "\ndef ", 1).rstrip("\n")
            b = ("/- Hand-written model: see `Libssz/SszTypes/SmallVecModel.lean`. -/\n"
                 + b + " :=\n  " + MODELS.pop(name))
        out.append(b)
    return "\n\n".join(out)


def universes(src):
    """The `Type _` binders become `Type` (see above)."""
    return src.replace("Type _", "Type")


def main():
    folder = sys.argv[1]
    targets = [
        link.extraction(os.path.join(folder, "..", "..", "Merkle", "Code"), "libssz_merkle",
                        "tree"),
        link.extraction(os.path.join(folder, "..", "..", "Code"), "libssz_codec",
                        "codec"),
    ]
    counts = {}

    renames = {}
    # The opaque types from another crate (for example `ContainerEncoder`, used by the
    # `SszEncode` the macro derives) come in the TypesExternal template.
    types_template = os.path.join(folder, "TypesExternal_Template.lean")
    if os.path.exists(types_template):
        src = open(types_template, encoding="utf-8").read()
        src = src.replace(
            '-- This is a template file: rename it to "TypesExternal.lean" and fill the holes.',
            "-- Generated by scripts/complete_externals_types.py from the Aeneas template.")
        src = universes(src)
        src = link.link_blocks(src, OWN, targets, counts, renames,
                               linkable=lambda c: not from_smallvec(c))
        if TYPE in src:
            imports = "public import Aeneas\n"
            assert src.count(imports) == 1, "the TypesExternal header changed"
            src = src.replace(imports, imports + "public import Libssz.SszTypes.SmallVecModel\n")
            src = src.replace(TYPE, f"""/- Hand-written model: see `Libssz/SszTypes/SmallVecModel.lean`. -/
@[rust_type "smallvec::SmallVec"]
abbrev smallvec.SmallVec (A : Type) (Clause0_Item : Type) : Type :=
  {M}.SmallVec A Clause0_Item
""")
        assert "axiom" not in src, "a type was left unlinked in TypesExternal"
        open(os.path.join(folder, "TypesExternal.lean"), "w", encoding="utf-8").write(src)
        os.remove(types_template)

    types = os.path.join(folder, "Types.lean")
    src = open(types, encoding="utf-8").read()
    imports = "public import Aeneas\n"
    assert src.count(imports) == 1, "the Types.lean header changed"
    src = src.replace(imports, imports + "public import Libssz.Merkle.Code.Funs\n")
    src = link.link_blocks(universes(src), OWN, targets, counts, renames,
                           linkable=lambda c: not from_smallvec(c))
    src = link.rename(src, renames)
    open(types, "w", encoding="utf-8").write(src)

    funs = os.path.join(folder, "Funs.lean")
    src = universes(link.rename(open(funs, encoding="utf-8").read(), renames))
    src = link.link_blocks(src, OWN, targets, counts, linkable=lambda c: not from_smallvec(c))
    open(funs, "w", encoding="utf-8").write(src)

    template = os.path.join(folder, "FunsExternal_Template.lean")
    src = open(template, encoding="utf-8").read()
    src = src.replace(
        '-- This is a template file: rename it to "FunsExternal.lean" and fill the holes.',
        "-- Generated by scripts/complete_externals_types.py from the Aeneas template.")
    opens = "open libssz_types\n"
    assert src.count(opens) == 1, "the header of the functions template changed"
    src = src.replace(opens, opens + "namespace libssz_types\n")
    src = link.link_blocks(universes(link.rename(src, renames)), OWN, targets, counts,
                           linkable=lambda c: not from_smallvec(c))
    src = models(src)
    src = src.rstrip("\n") + "\n\nend libssz_types\n"
    assert "axiom" not in src, "a hole was left unlinked in FunsExternal"
    open(os.path.join(folder, "FunsExternal.lean"), "w", encoding="utf-8").write(src)
    os.remove(template)
    print("linked with " + "; with ".join(f"{k}: {v}" for k, v in counts.items()))


if __name__ == "__main__":
    main()

"""Complete libssz's FunsExternal.lean from the template that Aeneas generates.

Usage: python3 complete_externals_codec.py FunsExternal_Template.lean FunsExternal.lean

libssz uses no iterators, closures or `unsafe`: the only thing Aeneas leaves
untranslated is `Vec::reserve`, which its library does not model. It is defined as the
identity. If the template contains any other `axiom`, the script fails: it has to be
inspected by hand.
"""
import sys

src = open(sys.argv[1]).read()
src = src.replace(
    '-- This is a template file: rename it to "FunsExternal.lean" and fill the holes.',
    "-- Generated by scripts/complete_externals_codec.py from the Aeneas template.")

OLD = """@[rust_fun "alloc::vec::{alloc::vec::Vec<@T>}::reserve"]
axiom alloc.vec.Vec.reserve
  {T : Type _} (A : Type _) :
  alloc.vec.Vec T → Std.Usize → Result (alloc.vec.Vec T)
"""
NEW = """/- `Vec::reserve` only changes the *capacity* of the vector, which the Aeneas model does
not represent: in its library `Vec::with_capacity` is already `Vec::new`. That is why it
is the identity. That it does not fail is the same assumption as the rest of the model:
allocating memory never fails. It is the only hand-written function of this model. -/
@[rust_fun "alloc::vec::{alloc::vec::Vec<@T>}::reserve"]
def alloc.vec.Vec.reserve
  {T : Type _} (A : Type _) :
  alloc.vec.Vec T → Std.Usize → Result (alloc.vec.Vec T) :=
  fun v _ => ok v
"""
assert src.count(OLD) == 1, "the Vec::reserve axiom in the template changed"
src = src.replace(OLD, NEW)
assert "\naxiom " not in src, "the template contains new axioms: review by hand"
open(sys.argv[2], "w").write(src)

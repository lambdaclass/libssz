//! Differential tests of the AArch64 SHA-256 kernel of `ssz-merkle` (libssz,
//! `crates/ssz-merkle/src/neon.rs`). They run only on little-endian AArch64 (a Mac with Apple
//! Silicon, for example).
//!
//! The Lean proofs in `lean/Libssz/MerkleNeon/Proofs/` state that the Aeneas model of
//! `neon.rs` computes EthLib's `combine` *assuming* that the eight intrinsics of
//! `core::arch::aarch64` do what the hand-written models in
//! `lean/Libssz/MerkleNeon/Intrinsics.lean` say. This tests that assumption, and the rest of
//! the chain, against the processor:
//!
//! * `intrinsics_match_their_lean_models`: each intrinsic, executed by the processor, against
//!   the answer of its Lean model;
//! * `kernel_matches_its_lean_model_and_the_spec`: `Sha2Hasher` (which on this machine
//!   dispatches to the kernel) against the Aeneas model, against EthLib's `combine` and
//!   against the `sha2` crate, for one pair, two pairs, four pairs and whole layers (also in
//!   place and with short outputs, which must panic on both sides).
//!
//! This machine does not need Lean: Lean's answers are in `vectors/`, generated by
//! `scripts/gen_neon_vectors.py` running the `difftest-merkle-neon` executable (the script
//! also checked them against `hashlib`). Each line is `INPUT<tab>LEAN ANSWER`; the input
//! format is described in `lean/DiffTestMerkleNeon.lean`.
#![cfg(all(target_arch = "aarch64", target_endian = "little"))]

use core::arch::aarch64::{
    uint32x4_t, vaddq_u32, vdupq_n_u32, vgetq_lane_u32, vsetq_lane_u32, vsha256h2q_u32,
    vsha256hq_u32, vsha256su0q_u32, vsha256su1q_u32,
};

use merkle::{Sha256Hasher, Sha2Hasher};
use sha2::{Digest, Sha256};

type Node = [u8; 32];

fn has_kernel() -> bool {
    std::arch::is_aarch64_feature_detected!("neon")
        && std::arch::is_aarch64_feature_detected!("sha2")
}

fn hex(b: &[u8]) -> String {
    b.iter().map(|x| format!("{x:02x}")).collect()
}

fn unhex(s: &str) -> Vec<u8> {
    assert!(s.len().is_multiple_of(2), "hex of odd length: {s}");
    (0..s.len())
        .step_by(2)
        .map(|i| u8::from_str_radix(&s[i..i + 2], 16).expect("invalid hex"))
        .collect()
}

fn vec16(s: &str) -> [u8; 16] {
    unhex(s).try_into().expect("a vector is 16 bytes")
}

fn node(s: &str) -> Node {
    unhex(s).try_into().expect("a node is 32 bytes")
}

fn nodes(s: &str) -> Vec<Node> {
    if s == "-" {
        return Vec::new();
    }
    unhex(s)
        .chunks(32)
        .map(|c| c.try_into().expect("32-byte nodes"))
        .collect()
}

fn hex_nodes(ns: &[Node]) -> String {
    if ns.is_empty() {
        "-".to_string()
    } else {
        ns.iter().map(|n| hex(n)).collect()
    }
}

/// The 16 bytes of the vector as laid out in memory. Does not go through any intrinsic.
fn bytes_of(v: uint32x4_t) -> [u8; 16] {
    unsafe { core::mem::transmute(v) }
}

fn vec_of(b: [u8; 16]) -> uint32x4_t {
    unsafe { core::mem::transmute(b) }
}

#[target_feature(enable = "neon,sha2")]
fn add(a: uint32x4_t, b: uint32x4_t) -> uint32x4_t {
    vaddq_u32(a, b)
}

#[target_feature(enable = "neon,sha2")]
fn su0(a: uint32x4_t, b: uint32x4_t) -> uint32x4_t {
    vsha256su0q_u32(a, b)
}

#[target_feature(enable = "neon,sha2")]
fn su1(a: uint32x4_t, b: uint32x4_t, c: uint32x4_t) -> uint32x4_t {
    vsha256su1q_u32(a, b, c)
}

#[target_feature(enable = "neon,sha2")]
fn h(abcd: uint32x4_t, efgh: uint32x4_t, wk: uint32x4_t) -> uint32x4_t {
    vsha256hq_u32(abcd, efgh, wk)
}

#[target_feature(enable = "neon,sha2")]
fn h2(efgh: uint32x4_t, abcd: uint32x4_t, wk: uint32x4_t) -> uint32x4_t {
    vsha256h2q_u32(efgh, abcd, wk)
}

#[target_feature(enable = "neon,sha2")]
fn dup(x: u32) -> uint32x4_t {
    vdupq_n_u32(x)
}

/// The lanes are const generics: one branch per value.
#[target_feature(enable = "neon,sha2")]
fn get(lane: u32, v: uint32x4_t) -> u32 {
    match lane {
        0 => vgetq_lane_u32::<0>(v),
        1 => vgetq_lane_u32::<1>(v),
        2 => vgetq_lane_u32::<2>(v),
        3 => vgetq_lane_u32::<3>(v),
        _ => panic!("lane {lane}"),
    }
}

#[target_feature(enable = "neon,sha2")]
fn set(lane: u32, x: u32, v: uint32x4_t) -> uint32x4_t {
    match lane {
        0 => vsetq_lane_u32::<0>(x, v),
        1 => vsetq_lane_u32::<1>(x, v),
        2 => vsetq_lane_u32::<2>(x, v),
        3 => vsetq_lane_u32::<3>(x, v),
        _ => panic!("lane {lane}"),
    }
}

/// The lines of a file in `vectors/`: the input (split into words) and Lean's answer.
fn cases(file: &str) -> Vec<(Vec<String>, String)> {
    let path = format!("{}/vectors/{file}", env!("CARGO_MANIFEST_DIR"));
    let text = std::fs::read_to_string(&path)
        .unwrap_or_else(|_| panic!("{path} not found: run scripts/gen_neon_vectors.py"));
    text.lines()
        .map(|line| {
            let (input, lean) = line.split_once('\t').expect("missing Lean answer");
            (
                input.split(' ').map(str::to_string).collect(),
                lean.to_string(),
            )
        })
        .collect()
}

/// Counts and prints the first mismatches.
fn report(what: &str, total: usize, bad: &[String]) -> usize {
    for b in bad.iter().take(10) {
        println!("{b}");
    }
    println!("{what}: {total} cases, {} mismatches", bad.len());
    bad.len()
}

#[test]
fn intrinsics_match_their_lean_models() {
    assert!(
        has_kernel(),
        "this processor lacks the SHA-256 instructions: the intrinsics cannot be tested"
    );
    let all = cases("neon-intrinsics.txt");
    let mut count = std::collections::BTreeMap::new();
    let mut bad = Vec::new();
    for (w, lean) in &all {
        let v = |i: usize| vec_of(vec16(&w[i]));
        let word = |i: usize| u32::from_str_radix(&w[i], 16).expect("u32 in hex");
        let lane = |i: usize| w[i].parse::<u32>().expect("lane");
        let got = unsafe {
            match w[0].as_str() {
                "add" => hex(&bytes_of(add(v(1), v(2)))),
                "su0" => hex(&bytes_of(su0(v(1), v(2)))),
                "su1" => hex(&bytes_of(su1(v(1), v(2), v(3)))),
                "h" => hex(&bytes_of(h(v(1), v(2), v(3)))),
                "h2" => hex(&bytes_of(h2(v(1), v(2), v(3)))),
                "dup" => hex(&bytes_of(dup(word(1)))),
                "get" => format!("{:08x}", get(lane(1), v(2))),
                "set" => hex(&bytes_of(set(lane(1), word(2), v(3)))),
                op => panic!("unknown operation {op}"),
            }
        };
        *count.entry(w[0].clone()).or_insert(0usize) += 1;
        if got != *lean {
            bad.push(format!(
                "PROCESSOR ≠ LEAN  {}\n    processor: {got}\n    Lean:      {lean}",
                w.join(" ")
            ));
        }
    }
    println!("cases per intrinsic: {count:?}");
    let n = report("intrinsics: processor vs Lean model", all.len(), &bad);
    assert_eq!(
        n, 0,
        "{n} mismatches between the processor and the Lean models"
    );
}

fn sha2_pair(a: &Node, b: &Node) -> Node {
    let mut h = Sha256::new();
    h.update(a);
    h.update(b);
    h.finalize().into()
}

/// Rust's `hash_layer`; `None` if it panics.
fn rust_layer(below: &[Node], level: &[Node], in_place: bool, zero: &Node) -> Option<Vec<Node>> {
    let mut out = level.to_vec();
    let run = std::panic::AssertUnwindSafe(|| {
        if in_place {
            Sha2Hasher.hash_layer_in_place(&mut out, zero)
        } else {
            Sha2Hasher.hash_layer(below, &mut out, zero)
        }
    });
    std::panic::catch_unwind(run).ok()?;
    Some(out)
}

#[test]
fn kernel_matches_its_lean_model_and_the_spec() {
    assert!(
        has_kernel(),
        "this processor lacks the SHA-256 instructions: `Sha2Hasher` would not use the kernel"
    );
    std::panic::set_hook(Box::new(|_| {}));
    let all = cases("neon-kernel.txt");
    let mut count = std::collections::BTreeMap::new();
    let mut bad = Vec::new();
    for (w, lean) in &all {
        *count.entry(w[0].clone()).or_insert(0usize) += 1;
        let got = match w[0].as_str() {
            // One pair: the kernel (through `Sha2Hasher`) = sha2 = Aeneas model = EthLib. Lean
            // answers the last two separated by a tab.
            "pair" => {
                let (a, b) = (node(&w[1]), node(&w[2]));
                let got = Sha2Hasher.hash_pair(&a, &b);
                assert_eq!(got, sha2_pair(&a, &b), "kernel ≠ sha2");
                format!("{}\t{}", hex(&got), hex(&got))
            }
            // Two and four pairs: a layer of four and of eight nodes, which `hash_layer`
            // hashes with `hash_pairs_x2` and `hash_pairs_x4`.
            "pairs2" | "pairs4" => {
                let ns: Vec<Node> = w[1..].iter().map(|s| node(s)).collect();
                let mut out = vec![[0u8; 32]; ns.len() / 2];
                Sha2Hasher.hash_layer(&ns, &mut out, &[0u8; 32]);
                for (k, pair) in ns.chunks(2).enumerate() {
                    assert_eq!(out[k], sha2_pair(&pair[0], &pair[1]), "kernel ≠ sha2");
                }
                out.iter().map(|n| hex(n)).collect::<Vec<_>>().join(",")
            }
            // Whole layers: into another buffer (`layer 0 ZERO BELOW LEVEL`) and in place
            // (`layer 1 ZERO OTHER NODES`, where OTHER is not read).
            "layer" => {
                let zero = node(&w[2]);
                let got = if w[1] == "1" {
                    rust_layer(&[], &nodes(&w[4]), true, &zero)
                } else {
                    rust_layer(&nodes(&w[3]), &nodes(&w[4]), false, &zero)
                };
                got.map_or("PANIC".to_string(), |out| hex_nodes(&out))
            }
            op => panic!("unknown operation {op}"),
        };
        if got != *lean {
            bad.push(format!(
                "RUST ≠ LEAN  {}…\n    Rust: {}\n    Lean: {}",
                &w.join(" ")[..80.min(w.join(" ").len())],
                &got[..80.min(got.len())],
                &lean[..80.min(lean.len())]
            ));
        }
    }
    println!("cases: {count:?}");
    let n = report("kernel: Rust vs Aeneas model vs EthLib", all.len(), &bad);
    assert_eq!(n, 0, "{n} mismatches");
}

#!/usr/bin/env python3
"""List the code no property reached, merged over ephyra coverage pages.

ephyra writes one coverage page per property (EPHYRA_COVERAGE_HTML=<dir>).
Each page only says what that one property reached; this merges every page
in the given directories and prints:

- the tracked functions no property entered;
- inside the functions some property entered, the lines none executed.

Code generated by the derive macros is attributed to the `#[derive]` line,
so its line data says little; read the library crates' gaps. Functions in
the property files (`tests/`) are skipped.

usage: coverage-gaps.py [--match SUBSTRING] DIR [DIR ...]
"""

import argparse
import collections
import glob
import json
import os
import re

DATA = re.compile(r'<script id="data" type="application/json">(.*?)</script>', re.S)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("dirs", nargs="+", help="directories of ephyra coverage pages")
    parser.add_argument("--match", help="only report functions whose name contains this")
    args = parser.parse_args()

    line_inputs = collections.defaultdict(int)  # (file, line) -> most inputs
    fn_inputs = collections.defaultdict(int)  # function -> most inputs
    fn_file = {}
    fn_lines = collections.defaultdict(set)
    sources = {}

    pages = [p for d in args.dirs for p in sorted(glob.glob(os.path.join(d, "*.html")))]
    if not pages:
        raise SystemExit(f"no coverage pages in {', '.join(args.dirs)}")
    for page in pages:
        with open(page, encoding="utf-8") as f:
            match = DATA.search(f.read())
        if match is None:
            raise SystemExit(f"{page}: no coverage data")
        for entry in json.loads(match.group(1))["files"]:
            path = entry["display"]
            sources[path] = entry["source"]
            # The property files themselves: their generator closures run
            # outside the property and always read as never entered.
            if path.startswith("tests/"):
                continue
            for fn in entry["functions"]:
                name = fn["name"]
                fn_file[name] = path
                fn_inputs[name] = max(fn_inputs[name], fn["inputs"])
                for line, inputs, _executions in fn["lines"]:
                    line_inputs[(path, line)] = max(line_inputs[(path, line)], inputs)
                    fn_lines[name].add(line)

    def wanted(name):
        return args.match is None or args.match in name

    names = sorted(n for n in fn_inputs if wanted(n))
    never = [n for n in names if fn_inputs[n] == 0]
    print(f"{len(pages)} pages, {len(names)} functions, {len(never)} never entered")
    for name in never:
        print(f"  - {name}")

    print("\nlines never executed in entered functions:")
    seen = set()
    for name in names:
        if fn_inputs[name] == 0:
            continue
        path = fn_file[name]
        gaps = tuple(sorted(l for l in fn_lines[name] if line_inputs[(path, l)] == 0))
        if not gaps or (path, gaps) in seen:
            continue
        seen.add((path, gaps))
        print(f"  {path}  ({name})")
        for line in gaps:
            print(f"    {line:5}  {sources[path][line - 1].strip()}")


if __name__ == "__main__":
    main()
